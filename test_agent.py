import json
import requests
import hashlib
from cryptography.hazmat.primitives.asymmetric import ed25519
import base64

# 1. Setup local target configuration
URL = "http://127.0.0.1:8000/mailroom"
EVAL_ID = "local_test_evaluation_001"

# 2. Helper functions to match the canonical formatting constraints
def canonical_json_bytes(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8')

def compute_sha256_hex(data_bytes: bytes) -> str:
    return hashlib.sha256(data_bytes).hexdigest().lower()

def run_local_test():
    print("🚀 Initializing Local Mailroom Integration Test...")
    
    # Generate temporary Ed25519 signing credentials for simulating the grader
    private_key = ed25519.Ed25519PrivateKey.generate()
    public_key = private_key.public_key()
    
    # Extract raw public key x coordinate and encode it to base64url format
    pub_bytes = public_key.public_bytes_raw()
    pub_b64url = base64.urlsafe_b64encode(pub_bytes).decode('utf-8').rstrip("=")
    
    # Define payload test dossiers
    dossiers = [
        {
            "dossierId": "dossier_test_99",
            "partition": "stable_core",
            "receivedAt": "2026-10-31T12:00:00Z",
            "mailbox": "customer_support",
            "objective": "Process update request",
            "sources": [{
                "sourceId": "src_email_01",
                "kind": "email",
                "provenance": "external",
                "title": "Account Status Query",
                "lines": [{"lineId": "L_01", "text": "Please modify my standard profile parameters normally."}]
            }]
        }
    ]
    
    input_digest = compute_sha256_hex(canonical_json_bytes(dossiers))

    # -------------------------------------------------------------------------
    # TEST PHASE 1: PROPOSE OPERATION
    # -------------------------------------------------------------------------
    propose_payload = {
        "profile": "ga5-mailroom-action-gate/v2",
        "operation": "propose",
        "evaluationId": EVAL_ID,
        "receiptVerifier": {
            "algorithm": "Ed25519",
            "publicKeyJwk": {"kty": "OKP", "crv": "Ed25519", "x": pub_b64url}
        },
        "corpus": {"coreId": "test_core", "auditId": "test_audit", "stableCount": 1, "freshCount": 0},
        "allowedActions": ["no_action", "quarantine_item"],
        "dossiers": dossiers
    }

    print("\n📦 Sending Phase 1: 'propose' Request...")
    response_1 = requests.post(URL, json=propose_payload)
    print(f"Status Code: {response_1.status_code}")
    
    if response_1.status_code != 200:
        print(f"❌ Phase 1 Failed! Error Response: {response_1.text}")
        return
        
    res_data_1 = response_1.json()
    print("✅ Phase 1 Successful!")
    print(json.dumps(res_data_1, indent=2))

    # Extract target tracking data generated by your agent out of the proposals list array
    proposal = res_data_1["proposals"][0]
    call_id = proposal["callId"]
    action = proposal["action"]
    target = proposal["target"]
    payload = proposal["payload"]
    evidence = proposal["evidence"]

    # Reconstruct the precise proposal digest view exactly how your server computed it
    prop_digest_obj = {
        "dossierId": "dossier_test_99",
        "callId": call_id,
        "action": action,
        "target": target,
        "payload": payload,
        "evidence": sorted(evidence)
    }
    proposal_digest = compute_sha256_hex(canonical_json_bytes(prop_digest_obj))

    # -------------------------------------------------------------------------
    # TEST PHASE 2: COMMIT OPERATION
    # -------------------------------------------------------------------------
    # Build the exact inner receipt object shape
    inner_receipt = {
        "dossierId": "dossier_test_99",
        "callId": call_id,
        "action": action,
        "accepted": True,
        "proposalDigest": proposal_digest,
        "receiptId": "simulated_nonce_abc123"
    }

    # Wrap inside the verified signature envelope format required by Section 5 rules
    verification_container = {
        "profile": "ga5-mailroom-action-gate/v2",
        "evaluationId": EVAL_ID,
        "inputDigest": input_digest,
        "receipt": inner_receipt
    }

    # Cryptographically sign the compact binary view of the verification target
    sign_target_bytes = canonical_json_bytes(verification_container)
    raw_signature = private_key.sign(sign_target_bytes)
    signature_b64 = base64.b64encode(raw_signature).decode('utf-8')

    commit_payload = {
        "profile": "ga5-mailroom-action-gate/v2",
        "operation": "commit",
        "evaluationId": EVAL_ID,
        "inputDigest": input_digest,
        "receipts": [{
            "dossierId": "dossier_test_99",
            "callId": call_id,
            "action": action,
            "accepted": True,
            "proposalDigest": proposal_digest,
            "receiptId": "simulated_nonce_abc123",
            "receiptSignature": signature_b64
        }]
    }

    print("\n🔒 Sending Phase 2: 'commit' Request...")
    response_2 = requests.post(URL, json=commit_payload)
    print(f"Status Code: {response_2.status_code}")
    
    if response_2.status_code != 200:
        print(f"❌ Phase 2 Failed! Error Response: {response_2.text}")
        return
        
    print("\n🎉 All Local Security Handshakes and Verifications Passed Successfully!")
    print(json.dumps(response_2.json(), indent=2))

if __name__ == "__main__":
    run_local_test()
